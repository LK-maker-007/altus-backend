from __future__ import annotations

import uuid
from typing import ClassVar

from django.db import models

from apps.core.models import ComplexScopedModel, TimestampedModel


class TicketCategory(models.TextChoices):
    ELECTRICAL = "electrical", "Electrical"
    PLUMBING = "plumbing", "Plumbing"
    CARPENTRY = "carpentry", "Carpentry"
    OTHER = "other", "Other"


class TicketStatus(models.TextChoices):
    OPEN = "open", "Open"
    IN_PROGRESS = "in_progress", "In Progress"
    RESOLVED = "resolved", "Resolved"
    CLOSED = "closed", "Closed"


class MaintenanceTicket(ComplexScopedModel, TimestampedModel):
    unit = models.ForeignKey(
        "core.Unit",
        on_delete=models.RESTRICT,
        related_name="maintenance_tickets",
    )
    raised_by = models.ForeignKey(
        "users.User",
        on_delete=models.RESTRICT,
        related_name="raised_tickets",
    )
    category = models.CharField(max_length=30, choices=TicketCategory.choices)
    title = models.CharField(max_length=200)
    description = models.TextField()
    status = models.CharField(
        max_length=20,
        choices=TicketStatus.choices,
        default=TicketStatus.OPEN,
    )
    # UUID v4 generated by the device at submit time. Prevents duplicate tickets
    # on client retry after a network disconnect. NULL for admin-created tickets.
    # PostgreSQL UNIQUE allows multiple NULLs — only non-null keys are deduplicated.
    client_idempotency_key = models.UUIDField(null=True, blank=True, unique=True)
    # Device-side submit timestamp. Informational only — never use for business logic.
    queued_at = models.DateTimeField(null=True, blank=True)
    resolved_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        indexes: ClassVar[list[models.Index]] = [
            # Resident view of their own tickets
            models.Index(fields=["unit", "status", "created_at"]),
            # Admin view of all tickets for a complex
            models.Index(fields=["complex", "status", "created_at"]),
            # Analytics query
            models.Index(fields=["complex", "created_at"]),
        ]
        constraints: ClassVar[list[models.BaseConstraint]] = [
            models.CheckConstraint(
                condition=models.Q(category__in=TicketCategory.values),
                name="ticket_category_valid",
            ),
            models.CheckConstraint(
                condition=models.Q(status__in=TicketStatus.values),
                name="ticket_status_valid",
            ),
        ]

    def __str__(self) -> str:
        return f"{self.title} [{self.status}]"


class TicketPhoto(models.Model):
    """
    Photo attached to a maintenance ticket. Stored in Cloudflare R2.
    CASCADE is intentional — photos have no meaning without their parent ticket.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    ticket = models.ForeignKey(
        MaintenanceTicket,
        on_delete=models.CASCADE,
        related_name="photos",
    )
    # Cloudflare R2 object URL. Max 3 photos per ticket enforced at service layer.
    photo_url = models.CharField(max_length=1000)
    uploaded_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        indexes: ClassVar[list[models.Index]] = [
            models.Index(fields=["ticket"]),
        ]

    def __str__(self) -> str:
        return f"Photo for {self.ticket_id}"


class TicketStatusHistory(models.Model):
    """
    Immutable audit log of status transitions. Append-only — never updated or deleted.
    CASCADE is intentional — history has no meaning without its parent ticket.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    ticket = models.ForeignKey(
        MaintenanceTicket,
        on_delete=models.CASCADE,
        related_name="status_history",
    )
    # WHY choices=TicketStatus.choices here:
    #   Every other status field in the codebase (MaintenanceTicket.status,
    #   Booking.status) has both choices= and a CheckConstraint. This field
    #   was the only exception, allowing an invalid string to corrupt the
    #   immutable audit log. Source: audit §P1 §TicketStatusHistory CheckConstraint.
    status = models.CharField(max_length=20, choices=TicketStatus.choices)
    changed_at = models.DateTimeField(auto_now_add=True)
    # Null for system-generated transitions
    changed_by = models.ForeignKey(
        "users.User",
        on_delete=models.RESTRICT,
        null=True,
        blank=True,
        related_name="ticket_status_changes",
    )

    class Meta:
        indexes: ClassVar[list[models.Index]] = [
            # Chronological status history for a ticket — primary read path
            models.Index(fields=["ticket", "changed_at"]),
        ]
        constraints: ClassVar[list[models.BaseConstraint]] = [
            models.CheckConstraint(
                condition=models.Q(status__in=TicketStatus.values),
                name="ticket_status_history_status_valid",
            ),
        ]

    def __str__(self) -> str:
        return f"{self.ticket_id} → {self.status}"
